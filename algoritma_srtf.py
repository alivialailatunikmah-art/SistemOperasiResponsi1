class Process:
    def __init__(self, pid, at, bt):
        self.pid = pid
        self.at = at
        self.bt = bt
        self.remaining_bt = bt
        self.wt = 0
        self.tat = 0
        self.completion_time = 0

def simulate_srtf():
    processes = [
        Process('P1', 0, 5),
        Process('P2', 1, 6),
        Process('P3', 3, 4),
        Process('P4', 4, 7),
        Process('P5', 6, 2)
    ]

    n = len(processes)
    current_time = 0
    completed = 0
    print("=== Simulasi Algoritma SRTF ===")

    while completed < n:
        available = [p for p in processes if p.at <= current_time and p.remaining_bt > 0]
        if not available:
            current_time += 1
            continue

        # Pilih proses dengan sisa waktu (remaining_bt) paling kecil
        curr = min(available, key=lambda x: x.remaining_bt)
        curr.remaining_bt -= 1
        current_time += 1

        if curr.remaining_bt == 0:
            completed += 1
            curr.completion_time = current_time
            curr.tat = curr.completion_time - curr.at
            curr.wt = curr.tat - curr.bt
            print(f"Proses {curr.pid}: CT = {curr.completion_time}, TAT = {curr.tat}, WT = {curr.wt}")

simulate_srtf()