class Process:
    def __init__(self, pid, at, bt, dl, ticket, share, period, p_type, priority):
        self.pid = pid
        self.at = at                  # Arrival Time
        self.bt = bt                  # Burst Time
        self.remaining_bt = bt        # Remaining Burst Time for SRTF/RR
        self.dl = dl                  # Deadline
        self.ticket = ticket          # Tickets for lottery scheduling
        self.share = share            # Share for Fair Share
        self.period = period          # Period
        self.type = p_type            # Interactive / Batch
        self.priority = priority      # Priority
        self.wt = 0                   # Waiting Time
        self.tat = 0                  # Turnaround Time
        self.completion_time = 0      # Completion Time

# Data Proses sesuai soal praktikum
def get_processes():
    return [
        Process('P1', 0, 5, 12, 15, 1, 20, 'Interactive', 2),
        Process('P2', 1, 6, 15, 10, 2, 10, 'Interactive', 1),
        Process('P3', 3, 4, 8, 20, 1, 8, 'Batch', 3),
        Process('P4', 4, 7, 18, 25, 1, 12, 'Batch', 4),
        Process('P5', 6, 2, 9, 5, 1, 6, 'Batch', 5),
    ]

def calculate_fcfs():
    processes = get_processes()
    current_time = 0
    print("=== Algoritma FCFS (First-Come, First-Served) ===")
    for p in processes:
        if current_time < p.at:
            current_time = p.at
        p.completion_time = current_time + p.bt
        p.tat = p.completion_time - p.at
        p.wt = p.tat - p.bt
        current_time = p.completion_time
        print(f"Proses {p.pid}: WT = {p.wt}, TAT = {p.tat}, CT = {p.completion_time}")

calculate_fcfs()