class Process:
    def __init__(self, pid, at, bt):
        self.pid = pid
        self.at = at
        self.bt = bt
        self.remaining_bt = bt
        self.wt = 0
        self.tat = 0
        self.completion_time = 0

def simulate_mlfq():
    processes = [
        Process('P1', 0, 5),
        Process('P2', 1, 6),
        Process('P3', 3, 4),
        Process('P4', 4, 7),
        Process('P5', 6, 2)
    ]

    processes.sort(key=lambda x: x.at)
    n = len(processes)
    current_time = 0
    completed = 0

    q1, q2, q3 = [], [], []
    idx = 0

    print("=== Simulasi Algoritma MLFQ ===")
    while idx < n and processes[idx].at <= current_time:
        q1.append(processes[idx])
        idx += 1

    while completed < n:
        if not q1 and not q2 and not q3:
            current_time = processes[idx].at
            q1.append(processes[idx])
            idx += 1

        if q1:
            curr = q1.pop(0)
            exec_time = min(2, curr.remaining_bt)
            curr.remaining_bt -= exec_time
            current_time += exec_time
            target_q = q2
        elif q2:
            curr = q2.pop(0)
            exec_time = min(4, curr.remaining_bt)
            curr.remaining_bt -= exec_time
            current_time += exec_time
            target_q = q3
        else:
            curr = q3.pop(0)
            exec_time = curr.remaining_bt
            curr.remaining_bt -= exec_time
            current_time += exec_time
            target_q = q3

        while idx < n and processes[idx].at <= current_time:
            q1.append(processes[idx])
            idx += 1

        if curr.remaining_bt > 0:
            target_q.append(curr)
        else:
            completed += 1
            curr.completion_time = current_time
            curr.tat = curr.completion_time - curr.at
            curr.wt = curr.tat - curr.bt
            print(f"Proses {curr.pid}: CT = {curr.completion_time}, TAT = {curr.tat}, WT = {curr.wt}")

simulate_mlfq()