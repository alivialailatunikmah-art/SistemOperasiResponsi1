class Process:
    def __init__(self, pid, at, bt, share):
        self.pid = pid
        self.at = at
        self.bt = bt
        self.remaining_bt = bt
        self.share = share
        self.wt = 0
        self.tat = 0
        self.completion_time = 0

def simulate_fair_share():
    processes = [
        Process('P1', 0, 5, 1),
        Process('P2', 1, 6, 2),
        Process('P3', 3, 4, 1),
        Process('P4', 4, 7, 1),
        Process('P5', 6, 2, 1)
    ]

    processes.sort(key=lambda x: x.at)
    queue = []
    current_time = 0
    completed = 0
    n = len(processes)
    idx = 0

    print("=== Simulasi Algoritma Proportional / Fair Share ===")
    while idx < n and processes[idx].at <= current_time:
        queue.append(processes[idx])
        idx += 1

    while completed < n:
        if not queue:
            current_time = processes[idx].at
            queue.append(processes[idx])
            idx += 1

        curr = queue.pop(0)
        # Quantum proporsional dikali dengan nilai share
        quantum = curr.share * 2
        exec_time = min(quantum, curr.remaining_bt)
        curr.remaining_bt -= exec_time
        current_time += exec_time

        while idx < n and processes[idx].at <= current_time:
            queue.append(processes[idx])
            idx += 1

        if curr.remaining_bt > 0:
            queue.append(curr)
        else:
            completed += 1
            curr.completion_time = current_time
            curr.tat = curr.completion_time - curr.at
            curr.wt = curr.tat - curr.bt
            print(f"Proses {curr.pid} (Share={curr.share}): CT = {curr.completion_time}, TAT = {curr.tat}, WT = {curr.wt}")

simulate_fair_share()